// Bundles the stage kit runtime (src/stage/kit.js) and anime.js v4 (MIT, the
// kit's engine) into src/stage/stage.generated.ts as strings, so hosts can
// register them for scripted html clips without any network at render time.
//
//   node scripts/bundle-stage.mjs          write the file
//   node scripts/bundle-stage.mjs --check  exit 1 if it's out of date
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { createRequire } from "node:module";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const OUT = join(here, "../src/stage/stage.generated.ts");
const require = createRequire(import.meta.url);

function bundle() {
  const animePkg = require.resolve("animejs/package.json");
  const animeDir = dirname(animePkg);
  const version = JSON.parse(readFileSync(animePkg, "utf8")).version;
  const anime = readFileSync(join(animeDir, "dist/bundles/anime.umd.min.js"), "utf8");
  const kit = readFileSync(join(here, "../src/stage/kit.js"), "utf8");
  return [
    "// Generated by scripts/bundle-stage.mjs from src/stage/kit.js and animejs. Don't edit.",
    "// anime.js is MIT licensed (Julian Garnier); its licence header is kept in ANIME_SOURCE.",
    "",
    `export const ANIME_VERSION = ${JSON.stringify(version)};`,
    `export const ANIME_SOURCE: string = ${JSON.stringify(anime)};`,
    `export const STAGE_KIT_SOURCE: string = ${JSON.stringify(kit)};`,
    `/** A fingerprint of the kit source: hosts that bundle the kit expose it so a stale bundle can be told from a current one. */`,
    `export const STAGE_KIT_HASH = ${JSON.stringify(createHash("sha1").update(kit).digest("hex").slice(0, 12))};`,
    "",
  ].join("\n");
}

const out = bundle();
if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== out) {
    console.error("src/stage/stage.generated.ts is out of date: run `pnpm --filter @miraiclip/renderer stage`");
    process.exit(1);
  }
} else {
  writeFileSync(OUT, out);
  console.log(`wrote ${relative(process.cwd(), OUT)}`);
}
