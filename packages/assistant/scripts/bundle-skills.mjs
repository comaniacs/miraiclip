// Bundles the Miraiclip plugin's skills (plugins/miraiclip/skills) into
// src/skills.generated.ts as MIRAICLIP_SKILLS, for apps that run the
// assistant in an editor.
//
// Only skill folders with an EDITOR.md are bundled: that's the in-editor
// playbook (SKILL.md is the Claude Code one, which drives a CLI and an MCP
// server the editor doesn't have). Every other .md in the folder (reference/…)
// is bundled as one of the skill's files.
//
//   node scripts/bundle-skills.mjs          write the file
//   node scripts/bundle-skills.mjs --check  exit 1 if it's out of date
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const ROOT = join(here, "../../../plugins/miraiclip/skills");
const OUT = join(here, "../src/skills.generated.ts");

function frontMatter(text) {
  const m = /^---\n([\s\S]*?)\n---\n?/.exec(text.replace(/^﻿/, "").replace(/\r\n/g, "\n"));
  const data = {};
  if (!m) return { data, body: text.trim() };
  for (const line of m[1].split("\n")) {
    const kv = /^([A-Za-z0-9_-]+):\s*(.*)$/.exec(line);
    if (!kv) continue;
    let v = kv[2].trim();
    if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) v = v.slice(1, -1);
    data[kv[1]] = v;
  }
  return { data, body: text.replace(/\r\n/g, "\n").slice(m[0].length).trim() };
}

function mdFiles(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) return mdFiles(p);
    return name.endsWith(".md") ? [p] : [];
  });
}

export function bundle() {
  const skills = [];
  for (const name of readdirSync(ROOT).sort()) {
    const dir = join(ROOT, name);
    if (!statSync(dir).isDirectory() || !existsSync(join(dir, "EDITOR.md"))) continue;
    const editor = frontMatter(readFileSync(join(dir, "EDITOR.md"), "utf8"));
    const claude = existsSync(join(dir, "SKILL.md")) ? frontMatter(readFileSync(join(dir, "SKILL.md"), "utf8")).data : {};
    const files = {};
    for (const p of mdFiles(dir).sort()) {
      const rel = relative(dir, p).replace(/\\/g, "/");
      if (rel === "EDITOR.md" || rel === "SKILL.md") continue;
      files[rel] = readFileSync(p, "utf8").replace(/\r\n/g, "\n");
    }
    const description = editor.data.description || claude.description;
    if (!description) throw new Error(`${name}: no description in EDITOR.md or SKILL.md`);
    skills.push({ name: editor.data.name || claude.name || name, description, instructions: editor.body, ...(Object.keys(files).length ? { files } : {}) });
  }
  return [
    "// Generated by scripts/bundle-skills.mjs from plugins/miraiclip/skills (EDITOR.md + reference files). Don't edit.",
    'import type { AssistantSkill } from "./skills.js";',
    "",
    "/** The Miraiclip plugin's skills, in their in-editor versions: pass to `createAssistant({ skills })`. */",
    `export const MIRAICLIP_SKILLS: readonly AssistantSkill[] = ${JSON.stringify(skills, null, 2)};`,
    "",
  ].join("\n");
}

const out = bundle();
if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== out) {
    console.error("src/skills.generated.ts is out of date: run `pnpm --filter @miraiclip/assistant skills`");
    process.exit(1);
  }
} else {
  writeFileSync(OUT, out);
  console.log(`wrote ${relative(process.cwd(), OUT)}`);
}
