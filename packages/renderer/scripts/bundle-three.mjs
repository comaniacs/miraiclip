// Bundles three.js (MIT, the three.js authors) and the few addons a sequence needs into
// src/stage/three.generated.ts as one string, so hosts can register `three` as a scripted
// library (data-libs="three") with no network at render time. The bundle defines a global THREE.
//
//   node scripts/bundle-three.mjs          write the file
//   node scripts/bundle-three.mjs --check  exit 1 if it's out of date
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const here = dirname(fileURLToPath(import.meta.url));
const OUT = join(here, "../src/stage/three.generated.ts");
const lf = (text) => text.replace(/\r\n/g, "\n");

const pkg = join(here, "../node_modules/three/package.json");
const version = JSON.parse(readFileSync(pkg, "utf8")).version;
const entry = [
  'export * from "three";',
  'export { RoundedBoxGeometry } from "three/examples/jsm/geometries/RoundedBoxGeometry.js";',
  'export { RoomEnvironment } from "three/examples/jsm/environments/RoomEnvironment.js";',
  'export { mergeGeometries } from "three/examples/jsm/utils/BufferGeometryUtils.js";',
].join("\n");
const res = await build({
  stdin: { contents: entry, resolveDir: here, loader: "js" },
  bundle: true, write: false, format: "iife", globalName: "THREE", minify: true, legalComments: "none", target: "es2020",
});
const banner = `/* three.js r${version.split(".")[1]} (${version}), MIT License, Copyright 2010-2024 three.js authors. https://threejs.org */\n`;
const code = lf(banner + res.outputFiles[0].text);
const out = [
  "// Generated by scripts/bundle-three.mjs from three.js. Don't edit.",
  "// three.js is MIT licensed (the three.js authors); its licence line is kept in THREE_SOURCE.",
  "",
  `export const THREE_VERSION = ${JSON.stringify(version)};`,
  `export const THREE_SOURCE: string = ${JSON.stringify(code)};`,
  "",
].join("\n");

if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (lf(current) !== out) {
    console.error("src/stage/three.generated.ts is out of date: run `pnpm --filter @miraiclip/renderer stage`");
    process.exit(1);
  }
} else {
  writeFileSync(OUT, out);
  console.log(`wrote ${relative(process.cwd(), OUT)} (${Math.round(code.length / 1024)} KB)`);
}
